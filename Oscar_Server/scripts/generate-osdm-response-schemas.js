'use strict';

/**
 * Generates OSDM_Simulator/tests/fixtures/osdm-response-schemas.json (#833):
 * the response bodies of every OSDM operation (success and error answers), for OSDM 3.6,
 * 3.7, 3.8 and 3.9, the versions of the simulator's providers (3.9: #858). The simulator's
 * tests check its answers against the version of the provider that gives
 * them. Never hand-edit the output.
 *
 * Same input and the same compact schema form as
 * generate-osdm-request-schemas.js (#736), whose functions it uses:
 *
 *   OSDM_SPEC_DIR=/tmp/osdm node scripts/generate-osdm-response-schemas.js
 */

const fs = require('node:fs');
const path = require('node:path');
const yaml = require('js-yaml');
const { compact, subtypesOf } = require('./generate-osdm-request-schemas');

const REPO = path.resolve(__dirname, '..', '..');
const SPEC_DIR = process.env.OSDM_SPEC_DIR
  || path.join(REPO, 'Documentation', 'Test_Coverage', 'OSDM_reference');
const OUT = path.join(REPO, 'OSDM_Simulator', 'tests', 'fixtures', 'osdm-response-schemas.json');
const VERSIONS = ['3.6', '3.7', '3.8', '3.9'];
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

// The JSON schema of a response, through components.responses.
function responseSchema(spec, node) {
  let n = node;
  if (n?.$ref?.startsWith('#/components/responses/')) n = spec.components?.responses?.[n.$ref.split('/').pop()];
  const content = n?.content;
  if (!content) return null;
  const json = Object.entries(content).find(([type]) => /json/i.test(type));
  return json?.[1]?.schema || null;
}

function forVersion(spec) {
  const all = spec.components?.schemas || {};
  const seen = new Set();
  const queue = [];
  const operations = [];
  for (const [p, item] of Object.entries(spec.paths || {})) {
    for (const method of METHODS) {
      const op = item?.[method];
      if (!op) continue;
      for (const [status, response] of Object.entries(op.responses || {})) {
        if (!/^\d{3}$/.test(status)) continue;
        const schema = responseSchema(spec, response);
        if (!schema) continue;
        operations.push({ method: method.toUpperCase(), path: p, status: Number(status), schema: compact(schema, all, seen, queue) });
      }
    }
  }
  const schemas = {};
  const subtypes = subtypesOf(all);
  while (queue.length) {
    const name = queue.shift();
    if (!all[name]) throw new Error(`unknown schema ${name}`);
    schemas[name] = compact(all[name], all, seen, queue);
    if (schemas[name].discriminator) {
      for (const sub of subtypes[name] || []) compact({ $ref: sub }, all, seen, queue);
    }
  }
  const sorted = {};
  for (const k of Object.keys(schemas).sort()) sorted[k] = schemas[k];
  return { operations, schemas: sorted };
}

function main() {
  const out = { $comment: 'GENERATED by Oscar_Server/scripts/generate-osdm-response-schemas.js (#833) - do not hand-edit.', versions: {} };
  for (const v of VERSIONS) {
    const file = path.join(SPEC_DIR, `OSDM-online-api-v${v}.0.yml`);
    if (!fs.existsSync(file)) throw new Error(`missing ${file}`);
    out.versions[`${v}.0`] = forVersion(yaml.load(fs.readFileSync(file, 'utf8')));
    console.log(`${v}.0: ${out.versions[`${v}.0`].operations.length} responses, ${Object.keys(out.versions[`${v}.0`].schemas).length} schemas`);
  }
  fs.writeFileSync(OUT, JSON.stringify(out) + '\n');
  console.log(`${OUT}: ${fs.statSync(OUT).size} bytes`);
}

if (require.main === module) main();

module.exports = { forVersion, responseSchema };
