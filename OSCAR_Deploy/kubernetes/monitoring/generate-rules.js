'use strict';

// The VPS's alert rules (OSCAR_Deploy/prometheus/alerts/*.yml) as the
// PrometheusRules a cluster's Prometheus Operator reads
// (monitoring/oscar/prometheus-rules.yaml), one per file, groups unchanged.
// Run it after changing a rule there:
//   node OSCAR_Deploy/kubernetes/monitoring/generate-rules.js
// kubernetes-monitoring.test.js fails until the two agree. It uses the
// js-yaml of Oscar_Server (npm ci there first).

const fs = require('node:fs');
const path = require('node:path');

const DEPLOY = path.resolve(__dirname, '../..');
const ALERTS = path.join(DEPLOY, 'prometheus/alerts');
const OUT = path.join(__dirname, 'oscar/prometheus-rules.yaml');
const yaml = require(require.resolve('js-yaml', { paths: [path.join(DEPLOY, '../Oscar_Server')] }));

const HEADER = `# Copyright [2026] [International Union of Railways (UIC)]
#
#    Licensed under the Apache License, Version 2.0 (the "License");
#    you may not use this file except in compliance with the License.
#    You may obtain a copy of the License at
#        http://www.apache.org/licenses/LICENSE-2.0

# Generated by OSCAR_Deploy/kubernetes/monitoring/generate-rules.js from
# OSCAR_Deploy/prometheus/alerts/*.yml: do not edit it by hand. The VPS's
# alert rules, one PrometheusRule per file, their groups as they are.
`;

// The rule files, in name order: [{ name, groups }].
function alertFiles() {
  return fs.readdirSync(ALERTS)
    .filter(f => f.endsWith('.yml'))
    .sort((a, b) => a.localeCompare(b))
    .map(f => ({ name: f.slice(0, -'.yml'.length), groups: yaml.load(fs.readFileSync(path.join(ALERTS, f), 'utf8')).groups }));
}

function prometheusRule({ name, groups }) {
  return {
    apiVersion: 'monitoring.coreos.com/v1',
    kind: 'PrometheusRule',
    metadata: { name, namespace: 'monitoring', labels: { 'app.kubernetes.io/part-of': 'oscar-monitoring' } },
    spec: { groups },
  };
}

function render() {
  const docs = alertFiles().map(f => yaml.dump(prometheusRule(f), { lineWidth: -1, noRefs: true }));
  return HEADER + docs.map(d => `---\n${d}`).join('');
}

if (require.main === module) {
  fs.writeFileSync(OUT, render());
  process.stdout.write(`${path.relative(DEPLOY, OUT)} written\n`);
}

module.exports = { render, alertFiles, OUT };
